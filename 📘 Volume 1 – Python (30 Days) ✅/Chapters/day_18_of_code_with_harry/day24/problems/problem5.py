# 5. Moderate – Tuple Slicing

# Question:

# Create the tuple:

# numbers = (10,20,30,40,50,60,70,80)

# Print:

# First four elements
# Last three elements
# Elements from index 2 to 5
# Every second element using slicing


numbers = (10,20,30,40,50,60,70,80)

print(numbers[:4])
print(numbers[-3:])
print(numbers[2:6])
print(numbers[::2])